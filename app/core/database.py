# Импортируем необходимые компоненты из SQLAlchemy
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase

# Импортируем настройки из нашего приложения
from app.core.config import settings

# 1. СОЗДАЕМ ДВИЖОК (ENGINE)
# =========================
# create_async_engine() - это "фабрика" для создания подключений к БД
# Аналогия: как будто создаем мотор для машины

engine = create_async_engine(
    settings.DATABASE_URL,  # Куда подключаться (URL базы данных)
    echo=False              # Нужно ли выводить SQL запросы в консоль
)

# Что происходит внутри:
# 1. Создается "движок" - объект, который управляет всеми соединениями с БД
# 2. Движок содержит ПУЛ СОЕДИНЕНИЙ (connection pool) - набор готовых подключений
# 3. Когда нужно выполнить запрос, движок берет свободное соединение из пула
# 4. После выполнения - возвращает соединение обратно в пул

# Почему async? Потому что работа с БД - это I/O операция
# (ожидание ответа от базы), которая может блокировать выполнение

# 2. СОЗДАЕМ ФАБРИКУ СЕССИЙ
# ==========================
# async_sessionmaker() - это фабрика для создания сессий
# Аналогия: как ключ от машины (каждый раз создаем новую сессию для работы)

AsyncSessionLocal = async_sessionmaker(
    bind=engine,           # Привязываем к нашему движку
    expire_on_commit=False # Важная настройка поведения объектов
)

# Что такое сессия (Session)?
# - Это единица работы с БД
# - Содержит все изменения, которые нужно сохранить
# - Управляет транзакциями (commit/rollback)
# - Отслеживает изменения объектов

# expire_on_commit=False означает:
# "После сохранения (commit) НЕ очищай данные объектов"
# По умолчанию True - после commit все данные становятся "устаревшими"
# и нужно заново загружать из БД. False удобнее для работы.

# 3. СОЗДАЕМ БАЗОВЫЙ КЛАСС ДЛЯ МОДЕЛЕЙ
# =====================================
# DeclarativeBase - это основа для всех наших таблиц (моделей)

class Base(DeclarativeBase):
    pass

# Что это дает:
# 1. Все наши модели (таблицы) будут наследоваться от этого класса
# 2. SQLAlchemy автоматически поймет, что это таблицы БД
